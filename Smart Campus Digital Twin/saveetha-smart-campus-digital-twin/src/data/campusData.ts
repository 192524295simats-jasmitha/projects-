function buildParkingSlots(): ParkingSlot[] {
  const slots: ParkingSlot[] = [];
  const rowConfigs: { z: number; zone: ParkingZone; prefix: string }[] = [
    { z: 34.0, zone: 'Zone A · Faculty', prefix: 'A' },
    { z: 42.5, zone: 'Zone B · Student', prefix: 'B' },
    { z: 51.0, zone: 'Zone C · Visitor & EV', prefix: 'C' },
  ];

  const vehicleTypes: Array<'Sedan' | 'SUV' | 'EV' | 'Compact'> = ['Sedan', 'SUV', 'EV', 'Compact'];
  const occupiedPattern = [
    true, true, false, true, true, true, false, true,
    true, false, true, true, false, true, true, false,
  ];

  rowConfigs.forEach((row, rIdx) => {
    for (let i = 0; i < 16; i++) {
      const x = -24.75 + i * 3.3;
      const isOccupied = occupiedPattern[(i + rIdx * 3) % occupiedPattern.length];
      const evCharger = rIdx === 2 && i >= 10;
      const numStr = String(i + 1).padStart(2, '0');
      const vType = isOccupied
        ? evCharger
          ? 'EV'
          : vehicleTypes[(i + rIdx) % vehicleTypes.length]
        : null;

      slots.push({
        id: `slot-${row.prefix}-${numStr}`,
        code: `${row.prefix}-${numStr}`,
        zone: row.zone,
        occupied: isOccupied,
        vehicleType: vType,
        vehiclePlate: isOccupied ? `TN-12-${String.fromCharCode(65 + rIdx)}${String.fromCharCode(68 + (i % 9))} ${1400 + i * 37 + rIdx * 111}` : null,
        entryTime: isOccupied ? `${7 + ((i + rIdx) % 3)}:${String((i * 11) % 60).padStart(2, '0')} AM` : null,
        evCharger,
        position3D: [x, 0.08, row.z],
        rotationY: rIdx % 2 === 0 ? 0 : Math.PI,
      });
    }
  });

  return slots;
}

